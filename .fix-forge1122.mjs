/**
 * Forge 1.12.2: this is a different world from every other target in the repo.
 *
 * Evidence, in order of authority:
 *
 *  - The official 1.12.x MDK (github.com/MinecraftForge/MinecraftForge, branch 1.12.x, mdk/):
 *    build.gradle uses `net.minecraftforge.gradle:ForgeGradle:3.+` with
 *    `mappings channel: 'snapshot', version: '20171003-1.12'` - NOT ForgeGradle 2.3, and NOT the
 *    Gradle 8/9 wrappers the other Forge targets use. mdk/src/main/resources/pack.mcmeta gives
 *    pack_format 3, and mdk/src/main/resources/mcmod.info gives the metadata file shape (1.12
 *    predates mods.toml).
 *  - javap on the mapped jar ForgeGradle actually produces
 *    (forge-1.12.2-14.23.5.2864_mapped_snapshot_20171003-1.12.jar):
 *      net.minecraft.item.Item implements net.minecraftforge.registries.IForgeRegistryEntry$Impl
 *      net.minecraft.creativetab.CreativeTabs has a public (String) constructor and abstract
 *        getTabIconItem()
 *      net.minecraft.item.Item has a no-arg constructor; setMaxStackSize/setMaxDamage/setCreativeTab
 *        return Item (chainable); Block.setHarvestLevel(String,int) returns void (NOT chainable)
 *      net.minecraftforge.fml.common.Mod$EventBusSubscriber has only {value, modid} - no bus
 *        selector - and GameData posts RegistryEvent on MinecraftForge.EVENT_BUS, so the default
 *        pairing is the correct one.
 *  - The real 1.12.2 client jar:
 *      assets/minecraft/textures/items/ and .../blocks/  -> PLURAL (singular from 1.13)
 *      assets/minecraft/models/item/apple.json -> {"parent":"item/generated", ...} - no
 *        "minecraft:" prefix on parents, and "layer0":"items/apple"
 *      assets/minecraft/loot_tables/ contains only chests/, entities/, gameplay/ - there are NO
 *        block loot tables before 1.14, and no tags/ at all before 1.13.
 *
 * Consequences for the adapter, all of which are per-version facts:
 *   - registration is RegistryEvent.Register<T>, not DeferredRegister (1.13+)
 *   - items/blocks are configured with setters, not an Item.Properties object
 *   - no datapack tags and no block loot tables, so those two slices are dropped
 *   - metadata is mcmod.info, not mods.toml
 *   - lang keys are item.<name>.name and tile.<name>.name
 */
