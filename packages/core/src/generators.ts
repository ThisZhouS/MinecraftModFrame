/**
 * Built-in content generators. They are version-agnostic: every Minecraft-specific fact
 * (API names, path conventions, code style) comes from the adapter record (Principle 1).
 */

export interface FileEntry {
  /** Relative posix path inside the generated project directory. */
  path: string;
  content: string;
  managed: boolean;
  executable: boolean;
  /** Which generator produced the file (traceability). */
  reason: string;
  /** When set, the file is copied from this absolute source path (binary assets: wrapper jar). */
  copyFrom?: string;
}

export interface GenerationPlan {
  adapterId: string;
  projectDirName: string;
  files: FileEntry[];
  warnings: string[];
}

export interface GenContext {
  spec: ModSpecT;
  adapter: AdapterRecordT;
  vars: Record<string, string>;
  warnings: string[];
}

/** Flatten spec+adapter into the global template variable set. */
export function buildVars(spec: ModSpecT, adapter: AdapterRecordT): Record<string, string> {
  const modId = spec.mod.modId;
  const ns = namespaceOf(spec);
  const description = spec.mod.description ?? `${spec.mod.name ?? modId} — generated by mcmodkit`;
  const gradleVars: Record<string, string> = {};
  for (const [k, v] of Object.entries(adapter.gradle)) {
    gradleVars[`gradle_${k}`] = v == null ? "" : typeof v === "string" ? v : JSON.stringify(v);
  }
  const packageName = renderTemplate(adapter.basePackagePattern, { modId, namespace: ns }, "basePackagePattern");
  const clientPackageName = `${packageName}.${adapter.clientSubpackage}`;
  const entityPackageName = `${packageName}.${adapter.entitySubpackage}`;
  // A client bootstrap is needed for key-bound screens and for entity renderers alike.
  const hasKeybinds =
    spec.ui.screens.some((s) => s.key !== undefined) || spec.content.entities.length > 0;
  const clientEntrypoint = hasKeybinds ? `${clientPackageName}.${adapter.mainClassSimpleName}Client` : "";
  return {
    modId,
    namespace: ns,
    modName: spec.mod.name ?? modId,
    modVersion: spec.mod.version,
    description,
    descriptionJson: JSON.stringify(description),
    authors: (spec.mod.authors ?? []).join(", "),
    authorsJson: JSON.stringify(spec.mod.authors ?? []),
    license: spec.mod.license ?? "MIT",
    mcVersion: spec.target.mcVersion,
    loader: spec.target.loader,
    loaderVersion: adapter.loaderVersion,
    javaVersion: String(adapter.java),
    mappings: adapter.mappings,
    gradleWrapperVersion: adapter.gradleWrapperVersion,
    packageName,
    packagePath: packageName.split(".").join("/"),
    clientPackageName,
    clientPackagePath: clientPackageName.split(".").join("/"),
    entityPackageName,
    entityPackagePath: entityPackageName.split(".").join("/"),
    clientEntrypoint,
    /** Quoted form for JSON templates; empty string keeps the JSON array valid. */
    clientEntrypointJson: clientEntrypoint === "" ? "" : JSON.stringify(clientEntrypoint),
    mainClassSimpleName: adapter.mainClassSimpleName,
    mainClassFq: `${packageName}.${adapter.mainClassSimpleName}`,
    ...gradleVars,
  };
}

function makeContext(spec: ModSpecT, adapter: AdapterRecordT): GenContext {
  return { spec, adapter, vars: buildVars(spec, adapter), warnings: [] };
}

interface ItemGenOut {
  files: FileEntry[];
  /** Class-body field declarations. */
  itemRegistrations: string[];
  /** Statements placed inside the registry class init() for the mod's own tab. */
  tabEntries: string[];
  /** Statements placed inside init() that hook vanilla creative tabs. */
  groupHooks: string[];
  langEntries: Record<string, string>;
}

function genItems(ctx: GenContext): ItemGenOut {
  const out: ItemGenOut = { files: [], itemRegistrations: [], tabEntries: [], groupHooks: [], langEntries: {} };
  for (const item of ctx.spec.content.items) {
    const constName = toPascalCase(item.id);
    const display = item.name ?? toDisplayName(item.id);
    const v = { ...ctx.vars, CONST: constName, CONST_UPPER: toScreamingSnake(constName), REG_NAME: item.id, DISPLAY: display, id: item.id };
    const settingsKey = item.maxCount != null ? "itemSettingsMaxCount" : "itemSettings";
    const settings = renderTemplate(ctx.adapter.templates[settingsKey]!, { ...v, MAX_COUNT: String(item.maxCount ?? 64) }, settingsKey);
    const groupExpr = item.group != null ? ctx.adapter.vanillaGroups[item.group] : undefined;
    let registration: string;
    if (item.group != null && groupExpr != null) {
      registration = renderTemplate(ctx.adapter.templates.itemRegistration!, { ...v, SETTINGS: settings }, "itemRegistration");
      out.groupHooks.push(renderTemplate(ctx.adapter.templates.itemRegistrationGroup!, { ...v, SETTINGS: settings, GROUP_EXPR: groupExpr }, "itemRegistrationGroup"));
    } else {
      if (item.group != null) {
        ctx.warnings.push(`item "${item.id}": unknown group "${item.group}" for adapter ${ctx.adapter.id}; placed in the mod's own tab`);
      }
      registration = renderTemplate(ctx.adapter.templates.itemRegistration!, { ...v, SETTINGS: settings }, "itemRegistration");
      out.tabEntries.push(renderTemplate(ctx.adapter.templates.tabEntryLineItem!, { ...v }, "tabEntryLineItem"));
    }
    out.itemRegistrations.push(registration);
    out.files.push({
      path: renderPath(ctx.adapter.contentPaths.itemModel, v, "contentPaths.itemModel"),
      content: renderTemplate(ctx.adapter.templates.itemModel!, v, "itemModel"),
      managed: true, executable: false, reason: `item:${item.id}:model`,
    });
    out.langEntries[renderTemplate(ctx.adapter.langKeys.item, { namespace: ctx.vars.namespace!, id: item.id }, "langKeys.item")] = display;
  }
  return out;
}

interface BlockGenOut {
  files: FileEntry[];
  blockRegistrations: string[];
  tabEntries: string[];
  langEntries: Record<string, string>;
}

function genBlocks(ctx: GenContext): BlockGenOut {
  const out: BlockGenOut = { files: [], blockRegistrations: [], tabEntries: [], langEntries: {} };
  const mineable: Record<string, string[]> = {};
  for (const block of ctx.spec.content.blocks) {
    const constName = toPascalCase(block.id);
    const display = block.name ?? toDisplayName(block.id);
    const v = { ...ctx.vars, CONST: constName, CONST_UPPER: toScreamingSnake(constName), REG_NAME: block.id, DISPLAY: display, id: block.id };
    const settingsKey = block.tool === "none" ? "blockSettingsNoTool" : "blockSettings";
    const settings = renderTemplate(
      ctx.adapter.templates[settingsKey]!,
      { ...v, HARDNESS: String(block.hardness), RESISTANCE: String(block.resistance), tool: block.tool },
      settingsKey,
    );
    out.blockRegistrations.push(renderTemplate(ctx.adapter.templates.blockRegistration!, { ...v, SETTINGS: settings }, "blockRegistration"));
    out.tabEntries.push(renderTemplate(ctx.adapter.templates.tabEntryLineBlock!, { ...v }, "tabEntryLineBlock"));
    out.files.push(
      {
        path: renderPath(ctx.adapter.contentPaths.blockState, v, "contentPaths.blockState"),
        content: renderTemplate(ctx.adapter.templates.blockState!, v, "blockState"),
        managed: true, executable: false, reason: `block:${block.id}:blockstate`,
      },
      {
        path: renderPath(ctx.adapter.contentPaths.blockModel, v, "contentPaths.blockModel"),
        content: renderTemplate(ctx.adapter.templates.blockModel!, v, "blockModel"),
        managed: true, executable: false, reason: `block:${block.id}:model`,
      },
      {
        path: renderPath(ctx.adapter.contentPaths.blockItemModel, v, "contentPaths.blockItemModel"),
        content: renderTemplate(ctx.adapter.templates.blockItemModel!, v, "blockItemModel"),
        managed: true, executable: false, reason: `block:${block.id}:itemModel`,
      },
      {
        path: renderPath(ctx.adapter.contentPaths.lootTable, v, "contentPaths.lootTable"),
        content: renderTemplate(ctx.adapter.templates.lootTable!, v, "lootTable"),
        managed: true, executable: false, reason: `block:${block.id}:loot`,
      },
    );
    if (block.tool !== "none") {
      (mineable[block.tool] ??= []).push(`${ctx.vars.namespace}:${block.id}`);
    }
    out.langEntries[renderTemplate(ctx.adapter.langKeys.block, { namespace: ctx.vars.namespace!, id: block.id }, "langKeys.block")] = display;
  }
  for (const [tool, values] of Object.entries(mineable)) {
    // Match the template indent (tabs) so generated tag files stay consistently formatted.
    const valuesJson = values.map((s) => `"${s}"`).join(",\n\t\t");
    out.files.push({
      path: renderPath(ctx.adapter.contentPaths.mineableTag, { ...ctx.vars, tool }, "contentPaths.mineableTag"),
      content: renderTemplate(ctx.adapter.templates.mineableTag!, { ...ctx.vars, VALUES: valuesJson, tool }, "mineableTag"),
      managed: true, executable: false, reason: `block:tags:mineable:${tool}`,
    });
  }
  return out;
}

interface UiGenOut {
  files: FileEntry[];
  langEntries: Record<string, string>;
}

/**
 * UI generator: turns spec.ui.screens into a client Screen class per screen plus one client
 * bootstrap that binds keys and opens the screens. Every loader/version detail (imports, event
 * classes, key input API, renderBackground signature) comes from adapter templates, so the engine
 * stays free of version branches (Principle 1).
 */
function genUi(ctx: GenContext, javaDir: string, rendererRegistrations: string[] = []): UiGenOut {
  const out: UiGenOut = { files: [], langEntries: {} };
  const screens = ctx.spec.ui.screens;
  if (screens.length === 0 && rendererRegistrations.length === 0) return out;
  const a = ctx.adapter;
  if (screens.length > 0 && (a.templates.screenClass === undefined || a.langKeys.screenTitle === undefined)) {
    throw new McmodError(
      "ADAPTER_INVALID",
      `Adapter ${a.id} does not support ui.screens: it declares no screen templates. Use list-versions to find an adapter that does.`,
      { adapterId: a.id },
    );
  }
  const fieldLines: string[] = [];
  const registerLines: string[] = [];
  const openLines: string[] = [];
  for (const screen of screens) {
    const className = `${a.mainClassSimpleName}${toPascalCase(screen.id)}Screen`;
    const display = screen.title ?? toDisplayName(screen.id);
    const titleKey = renderTemplate(a.langKeys.screenTitle!, { namespace: ctx.vars.namespace!, id: screen.id }, "langKeys.screenTitle");
    out.langEntries[titleKey] = display;
    const lineDraws = screen.lines
      .map((text, i) => {
        const lineKey = renderTemplate(
          a.langKeys.screenLine!,
          { namespace: ctx.vars.namespace!, id: screen.id, n: String(i + 1) },
          "langKeys.screenLine",
        );
        out.langEntries[lineKey] = text;
        return renderTemplate(a.templates.screenLineDraw!, { ...ctx.vars, LINE_KEY: lineKey, LINE_N: String(i + 1) }, "screenLineDraw");
      })
      .join("\n");
    out.files.push({
      path: `${javaDir}${a.clientSubpackage}/${className}.java`,
      content: renderTemplate(
        a.templates.screenClass!,
        {
          ...ctx.vars,
          SCREEN_CLASS: className,
          SCREEN_ID: screen.id,
          SCREEN_TITLE_KEY: titleKey,
          SCREEN_WIDTH: String(screen.width),
          SCREEN_HEIGHT: String(screen.height),
          SCREEN_LINE_DRAWS: lineDraws,
        },
        "screenClass",
      ),
      managed: true,
      executable: false,
      reason: `ui:${screen.id}:screen`,
    });
    if (screen.key === undefined) continue;
    const constName = `KEY_${screen.id.toUpperCase()}`;
    const keybindKey = renderTemplate(a.langKeys.keybind!, { namespace: ctx.vars.namespace!, id: screen.id }, "langKeys.keybind");
    const categoryKey = renderTemplate(a.langKeys.keybindCategory!, { namespace: ctx.vars.namespace! }, "langKeys.keybindCategory");
    const keyCode = renderTemplate(a.keyCodePattern, { KEY: screen.key }, "keyCodePattern");
    out.langEntries[keybindKey] = `Open ${display}`;
    out.langEntries[categoryKey] = ctx.vars.modName!;
    const bindVars = { ...ctx.vars, KEYBIND_CONST: constName, KEY_CODE: keyCode, KEYBIND_LANG_KEY: keybindKey, KEYBIND_CATEGORY_KEY: categoryKey };
    fieldLines.push(renderTemplate(a.templates.keybindField!, bindVars, "keybindField"));
    registerLines.push(renderTemplate(a.templates.keybindRegister!, bindVars, "keybindRegister"));
    openLines.push(renderTemplate(a.templates.screenOpenStatement!, { ...bindVars, SCREEN_CLASS: className }, "screenOpenStatement"));
  }
  if (openLines.length > 0 || rendererRegistrations.length > 0) {
    out.files.push({
      path: `${javaDir}${a.clientSubpackage}/${a.mainClassSimpleName}Client.java`,
      content: renderTemplate(
        a.templates.clientBootstrap!,
        {
          ...ctx.vars,
          KEYBIND_FIELDS: fieldLines.join("\n"),
          KEYBIND_REGISTRATIONS: registerLines.join("\n"),
          SCREEN_OPEN_BODY: openLines.join("\n"),
          ENTITY_RENDERER_REGISTRATIONS: rendererRegistrations.join("\n"),
        },
        "clientBootstrap",
      ),
      managed: true,
      executable: false,
      reason: "ui:client-bootstrap",
    });
  }
  return out;
}

interface RecipeGenOut {
  files: FileEntry[];
  /** recipe id -> produced resource location (feeds advancement icons). */
  results: Map<string, string>;
}

function knownContentIds(ctx: GenContext): Set<string> {
  return new Set<string>([
    ...ctx.spec.content.items.map((i) => i.id),
    ...ctx.spec.content.blocks.map((b) => b.id),
  ]);
}

/**
 * Accept a declared content id, or pass an explicit "ns:path" / "#ns:tag" through unchanged.
 * Unknown bare ids are a spec error listing the known ids, so an agent can fix it unattended.
 */
function resolveItemRef(ctx: GenContext, ref: string, where: string): { value: string; isTag: boolean } {
  if (ref.startsWith("#")) return { value: ref.slice(1), isTag: true };
  if (ref.includes(":")) return { value: ref, isTag: false };
  const known = knownContentIds(ctx);
  if (!known.has(ref)) {
    throw new McmodError(
      "SPEC_INVALID",
      where +
        ': "' +
        ref +
        '" is neither declared in this spec nor an explicit resource location. Add it to content.items/blocks, or write "minecraft:' +
        ref +
        '" to mean a vanilla item.',
      { where, ref, known: [...known] },
    );
  }
  return { value: ctx.vars.namespace + ":" + ref, isTag: false };
}

/** Vanilla ingredient form: {item: ...} or {tag: ...} (identical on 1.20.1 and 1.21.1). */
function ingredientJson(r: { value: string; isTag: boolean }): string {
  return JSON.stringify(r.isTag ? { tag: r.value } : { item: r.value });
}


const COOKING_DEFAULT_TICKS: Record<string, number> = { smelting: 200, blasting: 100, smoking: 100, campfire_cooking: 600 };

/**
 * Recipe generator: one JSON file per recipe. The file format is stable across 1.20.1/1.21.1; only the
 * datapack directory differs (recipes/ vs recipe/), which lives in contentPaths.recipe.
 */
function genRecipes(ctx: GenContext): RecipeGenOut {
  const out: RecipeGenOut = { files: [], results: new Map() };
  const recipes = ctx.spec.content.recipes;
  if (recipes.length === 0) return out;
  const a = ctx.adapter;
  if (a.contentPaths.recipe === undefined || a.templates.recipeShaped === undefined) {
    throw new McmodError(
      "ADAPTER_INVALID",
      `Adapter ${a.id} does not support content.recipes: it declares no recipe templates or paths`,
      { adapterId: a.id },
    );
  }
  const seen = new Set<string>();
  for (const recipe of recipes) {
    const where = `recipe "${recipe.id}"`;
    if (seen.has(recipe.id)) throw new McmodError("SPEC_INVALID", "Duplicate recipe id " + recipe.id);
    seen.add(recipe.id);
    const result = resolveItemRef(ctx, recipe.result, `${where}.result`);
    const groupLine = recipe.group === undefined ? "" : `\t"group": ${JSON.stringify(recipe.group)},\n`;
    const base = {
      ...ctx.vars,
      id: recipe.id,
      RECIPE_GROUP_LINE: groupLine,
      RESULT_ITEM: result.value,
      COUNT: String(recipe.count),
      EXPERIENCE: String(recipe.experience),
    };
    let templateKey: string;
    let vars: Record<string, string>;
    if (recipe.type === "crafting_shaped") {
      const pattern = recipe.pattern!;
      const width = Math.max(...pattern.map((row) => row.length));
      for (const row of pattern) {
        if (row.length !== width) {
          throw new McmodError("SPEC_INVALID", `${where}.pattern rows must all be the same length (got ${pattern.map((r) => r.length).join(", ")})`);
        }
      }
      const keyObj: Record<string, unknown> = {};
      for (const [ch, ref] of Object.entries(recipe.key!)) {
        const r = resolveItemRef(ctx, ref, `${where}.key.${ch}`);
        keyObj[ch] = r.isTag ? { tag: r.value } : { item: r.value };
      }
      templateKey = "recipeShaped";
      vars = { ...base, PATTERN_JSON: JSON.stringify(pattern), KEY_JSON: JSON.stringify(keyObj) };
    } else if (recipe.type === "crafting_shapeless") {
      const ings = recipe.ingredients!.map((ref, i) => ingredientJson(resolveItemRef(ctx, ref, `${where}.ingredients[${i}]`)));
      templateKey = "recipeShapeless";
      vars = { ...base, INGREDIENTS_JSON: "[" + ings.join(", ") + "]" };
    } else if (recipe.type === "stonecutting") {
      const ing = ingredientJson(resolveItemRef(ctx, recipe.ingredient!, `${where}.ingredient`));
      templateKey = "recipeStonecutting";
      vars = { ...base, INGREDIENT_JSON: ing };
    } else {
      const ing = ingredientJson(resolveItemRef(ctx, recipe.ingredient!, `${where}.ingredient`));
      templateKey = "recipeCooking";
      vars = {
        ...base,
        RECIPE_TYPE: `minecraft:${recipe.type}`,
        INGREDIENT_JSON: ing,
        COOKING_TIME: String(recipe.cookingTime ?? COOKING_DEFAULT_TICKS[recipe.type] ?? 200),
      };
    }
    const template = a.templates[templateKey];
    if (template === undefined) {
      throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} has no "${templateKey}" template but the spec asks for a ${recipe.type} recipe`, { adapterId: a.id, templateKey });
    }
    out.files.push({
      path: renderPath(a.contentPaths.recipe, { ...ctx.vars, id: recipe.id }, "contentPaths.recipe"),
      content: renderTemplate(template, vars, templateKey),
      managed: true,
      executable: false,
      reason: `recipe:${recipe.id}`,
    });
    out.results.set(recipe.id, result.value);
  }
  return out;
}

interface AdvancementGenOut {
  files: FileEntry[];
  langEntries: Record<string, string>;
}

/**
 * Advancement generator: criteria come from the recipes an advancement unlocks and/or the items it
 * watches for; parents are referenced by id. The JSON shape is shared by 1.20.1 and 1.21.1 — only the
 * datapack directory differs (advancements/ vs advancement/) and lives in contentPaths.advancement.
 */
function genAdvancements(ctx: GenContext, recipeResults: Map<string, string>): AdvancementGenOut {
  const out: AdvancementGenOut = { files: [], langEntries: {} };
  const advancements = ctx.spec.content.advancements;
  if (advancements.length === 0) return out;
  const a = ctx.adapter;
  if (a.contentPaths.advancement === undefined || a.templates.advancement === undefined || a.langKeys.advancementTitle === undefined ||
      a.templates.advancementItemPredicate === undefined ||
      a.templates.advancementTagPredicate === undefined) {
    throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} does not support content.advancements: it declares no advancement template, path or lang keys`, { adapterId: a.id });
  }
  const declared = new Set(advancements.map((x) => x.id));
  const seen = new Set<string>();
  for (const adv of advancements) {
    const where = `advancement "${adv.id}"`;
    if (seen.has(adv.id)) throw new McmodError("SPEC_INVALID", "Duplicate advancement id " + adv.id);
    seen.add(adv.id);
    const titleKey = renderTemplate(a.langKeys.advancementTitle, { namespace: ctx.vars.namespace!, id: adv.id }, "langKeys.advancementTitle");
    const descKey = renderTemplate(a.langKeys.advancementDescription!, { namespace: ctx.vars.namespace!, id: adv.id }, "langKeys.advancementDescription");
    out.langEntries[titleKey] = adv.title ?? toDisplayName(adv.id);
    out.langEntries[descKey] = adv.description ?? toDisplayName(adv.id) + " — generated by mcmodkit";
    let parentLine = "";
    if (adv.parent !== undefined) {
      const parent = adv.parent.includes(":") ? adv.parent : declared.has(adv.parent) ? `${ctx.vars.namespace}:${adv.parent}` : undefined;
      if (parent === undefined) {
        throw new McmodError("SPEC_INVALID", `${where}.parent "${adv.parent}" is neither a declared advancement in this spec nor an explicit resource location like "minecraft:story/root"`);
      }
      parentLine = `\t"parent": ${JSON.stringify(parent)},\n`;
    }
    const backgroundLine = adv.parent === undefined && adv.background !== undefined ? `\t\t"background": ${JSON.stringify(adv.background)},\n` : "";
    const fallbackIcon = ctx.spec.content.items[0] === undefined ? undefined : `${ctx.vars.namespace}:${ctx.spec.content.items[0].id}`;
    const iconRef = adv.icon ?? (adv.unlockRecipes.length > 0 ? recipeResults.get(adv.unlockRecipes[0]!) : undefined) ?? fallbackIcon;
    if (iconRef === undefined) {
      throw new McmodError("SPEC_INVALID", `${where}: cannot infer an icon — set icon, or unlock a recipe, or declare an item`);
    }
    const icon = resolveItemRef(ctx, iconRef, `${where}.icon`);
    const criteria: Record<string, unknown> = {};
    for (const rid of adv.unlockRecipes) {
      if (!recipeResults.has(rid)) {
        throw new McmodError("SPEC_INVALID", `${where}.unlockRecipes: "${rid}" is not a recipe declared in this spec`, { id: adv.id, recipe: rid });
      }
      criteria[`unlock_${rid}`] = { trigger: "minecraft:recipe_unlocked", conditions: { recipe: `${ctx.vars.namespace}:${rid}` } };
    }
    // The item-predicate JSON changed in 1.21 (object list -> plain string), so the fragment comes
    // from an adapter template and is parsed here, which also proves the template renders valid JSON.
    adv.hasItems.forEach((ref, i) => {
      const r = resolveItemRef(ctx, ref, `${where}.hasItems[${i}]`);
      const predicateKey = r.isTag ? "advancementTagPredicate" : "advancementItemPredicate";
      const predicateTemplate = a.templates[predicateKey];
      if (predicateTemplate === undefined) {
        throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} has no "${predicateKey}" template required for advancement item predicates`, { adapterId: a.id });
      }
      const predicateText = renderTemplate(predicateTemplate, { ...ctx.vars, ITEM_ID: r.value, TAG_ID: r.value }, predicateKey);
      let predicate: unknown;
      try {
        predicate = JSON.parse(predicateText);
      } catch {
        throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} template "${predicateKey}" must render valid JSON, got: ${predicateText}`, { adapterId: a.id, templateKey: predicateKey });
      }
      criteria["has_" + r.value.replace(/[:/]/g, "_")] = { trigger: "minecraft:inventory_changed", conditions: { items: [predicate] } };
    });
    const rewardsLine =
      adv.unlockRecipes.length === 0
        ? ""
        : `\t"rewards": ${JSON.stringify({ recipes: adv.unlockRecipes.map((rid) => `${ctx.vars.namespace}:${rid}`) })},\n`;
    const names = Object.keys(criteria);
    out.files.push({
      path: renderPath(a.contentPaths.advancement, { ...ctx.vars, id: adv.id }, "contentPaths.advancement"),
      content: renderTemplate(
        a.templates.advancement,
        {
          ...ctx.vars,
          ADV_PARENT_LINE: parentLine,
          ADV_BACKGROUND_LINE: backgroundLine,
          ADV_ICON_ITEM: icon.value,
          ADV_REWARDS_LINE: rewardsLine,
          ADV_TITLE_JSON: JSON.stringify({ translate: titleKey }),
          ADV_DESCRIPTION_JSON: JSON.stringify({ translate: descKey }),
          ADV_FRAME: adv.frame,
          ADV_SHOW_TOAST: String(adv.showToast),
          ADV_ANNOUNCE_TO_CHAT: String(adv.announceToChat),
          ADV_HIDDEN: String(adv.hidden),
          ADV_CRITERIA_JSON: JSON.stringify(criteria),
          ADV_REQUIREMENTS_JSON: JSON.stringify([names]),
        },
        "advancement",
      ),
      managed: true,
      executable: false,
      reason: `advancement:${adv.id}`,
    });
  }
  return out;
}

interface EntityGenOut {
  files: FileEntry[];
  entityRegistrations: string[];
  attributeHooks: string[];
  rendererRegistrations: string[];
  registryInitCalls: string[];
  langEntries: Record<string, string>;
}

/** Entity loot table JSON. The format is shared by 1.20.1 and 1.21.1; only the directory differs. */
function entityLootJson(ctx: GenContext, entity: { loot: { item: string; min: number; max: number; chance: number }[] }): string {
  const pools = entity.loot.map((drop) => {
    const ref = resolveItemRef(ctx, drop.item, `entity loot item`);
    const entry: Record<string, unknown> = { type: "minecraft:item", name: ref.value };
    if (drop.min !== 1 || drop.max !== 1) {
      // Vanilla always spells out the number-provider type; omitting it risks the "constant" default.
      entry.functions = [
        { function: "minecraft:set_count", count: { type: "minecraft:uniform", min: drop.min, max: drop.max } },
      ];
    }
    const pool: Record<string, unknown> = { rolls: 1, entries: [entry] };
    if (drop.chance < 1) pool.conditions = [{ condition: "minecraft:random_chance", chance: drop.chance }];
    return pool;
  });
  return JSON.stringify(pools);
}

/**
 * Entity generator: one mob class + renderer + loot table per entity, plus a single registry class.
 * Base class, MobCategory, attribute base and the client model all come from adapter data, so the engine
 * emits no version- or loader-specific Java itself (Principle 1).
 */
function genEntities(ctx: GenContext, javaDir: string): EntityGenOut {
  const out: EntityGenOut = { files: [], entityRegistrations: [], attributeHooks: [], rendererRegistrations: [], registryInitCalls: [], langEntries: {} };
  const entities = ctx.spec.content.entities;
  if (entities.length === 0) return out;
  const a = ctx.adapter;
  if (
    a.templates.entityClass === undefined ||
    a.templates.entitiesRegistryClass === undefined ||
    a.contentPaths.entityLootTable === undefined ||
    a.langKeys.entity === undefined
  ) {
    throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} does not support content.entities: it declares no entity templates, loot path or lang key`, { adapterId: a.id });
  }
  const entityDir = `${javaDir}${a.entitySubpackage}/`;
  const clientDir = `${javaDir}${a.clientSubpackage}/`;
  const seen = new Set<string>();
  for (const entity of entities) {
    const where = `entity "${entity.id}"`;
    if (seen.has(entity.id)) throw new McmodError("SPEC_INVALID", "Duplicate entity id " + entity.id);
    seen.add(entity.id);
    const kindKey = entity.kind;
    const kind = a.entityKinds[kindKey];
    if (kind === undefined) {
      throw new McmodError("ADAPTER_INVALID", `Adapter ${a.id} has no entityKinds entry for kind "${kindKey}"`, { adapterId: a.id, kind: kindKey });
    }
    const model = a.entityModels[entity.model];
    if (model === undefined) {
      throw new McmodError("SPEC_INVALID", `${where}.model "${entity.model}" is not offered by adapter ${a.id}; available: ${Object.keys(a.entityModels).join(", ")}`, { id: entity.id });
    }
    const cls = `${a.mainClassSimpleName}${toPascalCase(entity.id)}Entity`;
    const rendererCls = `${a.mainClassSimpleName}${toPascalCase(entity.id)}Renderer`;
    const constName = `${entity.id.toUpperCase()}`;
    const display = entity.name ?? toDisplayName(entity.id);
    const vars: Record<string, string> = {
      ...ctx.vars,
      id: entity.id,
      ENTITY_ID: entity.id,
      ENTITY_CLASS: cls,
      ENTITY_FQ: `${a.basePackagePattern.replace("{{modId}}", ctx.spec.mod.modId)}.${a.entitySubpackage}.${cls}`,
      ENTITY_CONST: constName,
      ENTITY_BASE_CLASS: kind.baseClass,
      ENTITY_ATTRIBUTE_BASE: kind.attributeBase,
      ENTITY_HEALTH: String(entity.health),
      ENTITY_SPEED: String(entity.speed),
      ENTITY_ATTACK_DAMAGE: String(entity.attackDamage),
      ENTITY_FOLLOW_RANGE: String(entity.followRange),
      ENTITY_WIDTH: String(entity.width),
      ENTITY_HEIGHT: String(entity.height),
      ENTITY_SHADOW: String(entity.shadow),
      ENTITY_TRACKING_RANGE: String(Math.max(4, Math.min(16, Math.ceil(entity.followRange / 2)))),
      ENTITY_CATEGORY: (entity.category ?? kind.category).toUpperCase(),
      RENDERER_CLASS: rendererCls,
      RENDERER_FQ: `${ctx.vars.clientPackageName}.${rendererCls}`,
      ENTITIES_CLASS: `${a.mainClassSimpleName}Entities`,
      ENTITIES_FQ: `${ctx.vars.packageName}.${a.mainClassSimpleName}Entities`,
      MODEL_CLASS: model.modelClass,
      MODEL_LAYER: model.modelLayer,
      LOOT_POOLS_JSON: entityLootJson(ctx, entity),
    };
    out.files.push(
      {
        path: `${entityDir}${cls}.java`,
        content: renderTemplate(a.templates.entityClass, vars, "entityClass"),
        managed: true, executable: false, reason: `entity:${entity.id}:class`,
      },
      {
        path: `${clientDir}${rendererCls}.java`,
        content: renderTemplate(a.templates.entityRendererClass!, vars, "entityRendererClass"),
        managed: true, executable: false, reason: `entity:${entity.id}:renderer`,
      },
      {
        path: renderPath(a.contentPaths.entityLootTable, { ...vars, id: entity.id }, "contentPaths.entityLootTable"),
        content: renderTemplate(a.templates.entityLootTable!, vars, "entityLootTable"),
        managed: true, executable: false, reason: `entity:${entity.id}:loot`,
      },
    );
    out.entityRegistrations.push(renderTemplate(a.templates.entityRegistration!, vars, "entityRegistration"));
    out.attributeHooks.push(renderTemplate(a.templates.entityAttributeHook!, vars, "entityAttributeHook"));
    out.rendererRegistrations.push(renderTemplate(a.templates.entityRendererRegistration!, vars, "entityRendererRegistration"));
    out.langEntries[renderTemplate(a.langKeys.entity, { namespace: ctx.vars.namespace!, id: entity.id }, "langKeys.entity")] = display;
  }
  const registryVars = {
    ...ctx.vars,
    ENTITY_REGISTRATIONS: out.entityRegistrations.join("\n"),
    ENTITY_ATTRIBUTE_HOOKS: out.attributeHooks.join("\n"),
    ENTITIES_CLASS: `${a.mainClassSimpleName}Entities`,
    ENTITIES_FQ: `${ctx.vars.packageName}.${a.mainClassSimpleName}Entities`,
  };
  out.files.push({
    path: `${javaDir}${a.mainClassSimpleName}Entities.java`,
    content: renderTemplate(a.templates.entitiesRegistryClass!, registryVars, "entitiesRegistryClass"),
    managed: true, executable: false, reason: "entities-registry",
  });
  out.registryInitCalls.push(renderTemplate(a.templates.entitiesRegistryInit!, registryVars, "entitiesRegistryInit"));
  return out;
}
export interface PlanOptions {
  /**
   * Resolve an adapter asset key to an absolute file path. Required when the adapter declares
   * assetFiles (e.g. the gradle wrapper jar) - the adapters package supplies this.
   */
  resolveAsset?: (assetKey: string) => string;
}

/** Pure: spec + adapter -> file plan (no I/O). */
export function planGeneration(spec: ModSpecT, adapter: AdapterRecordT, options: PlanOptions = {}): GenerationPlan {
  const ctx = makeContext(spec, adapter);
  const files: FileEntry[] = [];

  // Duplicate content ids would collide in registries, models and lang — reject early.
  const seenIds = new Map<string, string>();
  for (const [kind, list] of [["item", spec.content.items], ["block", spec.content.blocks]] as const) {
    for (const c of list) {
      const prev = seenIds.get(c.id);
      if (prev != null) {
        throw new McmodError("SPEC_INVALID", `Duplicate content id "${c.id}" (${prev} and ${kind}); ids must be unique across items and blocks`, { id: c.id });
      }
      seenIds.set(c.id, kind);
    }
  }

  // The adapter owns the source layout: sibling files live next to its main class. Never hard-code the
  // java source root here.
  const mainClassFile = adapter.projectFiles.find((f) => f.template === "mainClass");
  if (mainClassFile === undefined) {
    throw new McmodError("ADAPTER_INVALID", `Adapter ${adapter.id} has no projectFile using the "mainClass" template`, { adapterId: adapter.id });
  }
  const javaDir = renderPath(mainClassFile.path, ctx.vars, "mainClass").replace(/[^/]+$/, "");
  // Entities are generated first: the skeleton (registry init) and the client bootstrap (renderers)
  // both consume injection points that only they can fill.
  const entities = genEntities(ctx, javaDir);
  const injectionVars: Record<string, string> = { REGISTRY_INIT_CALLS: entities.registryInitCalls.join("\n") };

  for (const f of adapter.projectFiles) {
    files.push({
      path: renderPath(f.path, ctx.vars, `projectFile:${f.path}`),
      content: renderTemplate(adapter.templates[f.template]!, { ...ctx.vars, ...injectionVars }, f.template),
      managed: f.managed,
      executable: f.executable,
      reason: "skeleton",
    });
  }

  for (const a of adapter.assetFiles) {
    if (!options.resolveAsset) {
      throw new McmodError(
        "ADAPTER_INVALID",
        `Adapter ${adapter.id} requires asset "${a.asset}" but no asset resolver was provided (use @mcmodkit/adapters planProject)`,
        { asset: a.asset },
      );
    }
    files.push({
      path: renderPath(a.path, ctx.vars, `assetFile:${a.path}`),
      content: "",
      copyFrom: options.resolveAsset(a.asset),
      managed: true,
      executable: a.path.endsWith("gradlew"),
      reason: `asset:${a.asset}`,
    });
  }

  const items = genItems(ctx);
  const blocks = genBlocks(ctx);
  files.push(...items.files, ...blocks.files);

  const tabBlock = renderTemplate(adapter.templates.tabBlock!, { ...ctx.vars, TAB_ENTRIES: items.tabEntries.concat(blocks.tabEntries).join("\n") }, "tabBlock");
  files.push({
    path: `${javaDir}${adapter.mainClassSimpleName}Items.java`,
    content: renderTemplate(
      adapter.templates.itemsRegistryClass!,
      { ...ctx.vars, ITEM_REGISTRATIONS: items.itemRegistrations.join("\n"), TAB_BLOCK: tabBlock, ITEM_GROUP_HOOKS: items.groupHooks.join("\n") },
      "itemsRegistryClass",
    ),
    managed: true, executable: false, reason: "items-registry",
  });
  files.push({
    path: `${javaDir}${adapter.mainClassSimpleName}Blocks.java`,
    content: renderTemplate(adapter.templates.blocksRegistryClass!, { ...ctx.vars, BLOCK_REGISTRATIONS: blocks.blockRegistrations.join("\n") }, "blocksRegistryClass"),
    managed: true, executable: false, reason: "blocks-registry",
  });

  const ui = genUi(ctx, javaDir, entities.rendererRegistrations);
  const recipes = genRecipes(ctx);
  // Advancements consume recipe ids so they can reference "the recipe this unlocks" and derive an icon.
  const advancements = genAdvancements(ctx, recipes.results);
  files.push(...ui.files, ...recipes.files, ...advancements.files, ...entities.files);

  const langObj: Record<string, string> = {
    [renderTemplate(adapter.langKeys.itemGroup, { namespace: ctx.vars.namespace! }, "langKeys.itemGroup")]: ctx.vars.modName!,
    ...items.langEntries,
    ...blocks.langEntries,
    ...ui.langEntries,
    ...advancements.langEntries,
    ...entities.langEntries,
  };
  files.push({
    path: renderPath(adapter.contentPaths.lang, ctx.vars, "contentPaths.lang"),
    content: JSON.stringify(langObj, null, 2) + "\n",
    managed: true, executable: false, reason: "lang",
  });

  const seenPaths = new Set<string>();
  for (const f of files) {
    if (seenPaths.has(f.path)) {
      throw new McmodError("PLAN_INVALID", `Plan produced duplicate file path: ${f.path}`, { path: f.path });
    }
    seenPaths.add(f.path);
  }

  return { adapterId: adapter.id, projectDirName: spec.mod.modId, files, warnings: ctx.warnings };
}
