/**
 * Built-in content generators. They are version-agnostic: every Minecraft-specific fact
 * (API names, path conventions, code style) comes from the adapter record (Principle 1).
 */

export interface FileEntry {
  /** Relative posix path inside the generated project directory. */
  path: string;
  /** UTF-8 body; empty string for binary entries (see `bytes`). */
  content: string;
  managed: boolean;
  executable: boolean;
  /** Which generator produced the file (traceability). */
  reason: string;
  /** When set, the file is copied from this absolute source path (binary assets: wrapper jar). */
  copyFrom?: string;
  /** In-memory binary body (generated PNG textures). Takes precedence over `content`. */
  bytes?: Uint8Array;
}

export interface GenerationPlan {
  adapterId: string;
  projectDirName: string;
  files: FileEntry[];
  warnings: string[];
}

export interface GenContext {
  spec: ModSpecT;
  adapter: AdapterRecordT;
  vars: Record<string, string>;
  warnings: string[];
  /**
   * Pre-generated texture PNGs keyed by "<kind>:<id>" (see prefetchTextures). Supplied by the
   * caller so planning stays synchronous and free of I/O; absent = paint locally.
   */
  images?: Map<string, Uint8Array>;
}

/** Flatten spec+adapter into the global template variable set. */
export function buildVars(spec: ModSpecT, adapter: AdapterRecordT): Record<string, string> {
  const modId = spec.mod.modId;
  const ns = namespaceOf(spec);
  const description = spec.mod.description ?? `${spec.mod.name ?? modId} — generated by mcmodkit`;
  const gradleVars: Record<string, string> = {};
  for (const [k, v] of Object.entries(adapter.gradle)) {
    gradleVars[`gradle_${k}`] = v == null ? "" : typeof v === "string" ? v : JSON.stringify(v);
  }
  const packageName = renderTemplate(adapter.basePackagePattern, { modId, namespace: ns }, "basePackagePattern");
  const clientPackageName = `${packageName}.${adapter.clientSubpackage}`;
  const entityPackageName = `${packageName}.${adapter.entitySubpackage}`;
  const datagenPackageName = `${packageName}.${adapter.datagenSubpackage}`;
  // A client bootstrap is needed for key-bound screens and for entity renderers alike.
  const hasKeybinds =
    spec.ui.screens.some((s) => s.key !== undefined) || spec.content.entities.length > 0;
  const clientEntrypoint = hasKeybinds ? `${clientPackageName}.${adapter.mainClassSimpleName}Client` : "";
  // Fabric wires its data generator through a mod-metadata entrypoint; the other loaders scan annotations.
  const datagenEntrypoint = spec.datagen
    ? `${packageName}.${adapter.datagenSubpackage}.${adapter.mainClassSimpleName}DataGen`
    : "";
  return {
    modId,
    namespace: ns,
    modName: spec.mod.name ?? modId,
    modVersion: spec.mod.version,
    description,
    descriptionJson: JSON.stringify(description),
    authors: (spec.mod.authors ?? []).join(", "),
    authorsJson: JSON.stringify(spec.mod.authors ?? []),
    license: spec.mod.license ?? "MIT",
    mcVersion: spec.target.mcVersion,
    loader: spec.target.loader,
    loaderVersion: adapter.loaderVersion,
    javaVersion: String(adapter.java),
    mappings: adapter.mappings,
    gradleWrapperVersion: adapter.gradleWrapperVersion,
    packageName,
    packagePath: packageName.split(".").join("/"),
    clientPackageName,
    clientPackagePath: clientPackageName.split(".").join("/"),
    entityPackageName,
    entityPackagePath: entityPackageName.split(".").join("/"),
    datagenPackageName,
    datagenPackagePath: datagenPackageName.split(".").join("/"),
    clientEntrypoint,
    /** Quoted form for JSON templates; empty string keeps the JSON array valid. */
    clientEntrypointJson: clientEntrypoint === "" ? "" : JSON.stringify(clientEntrypoint),
    datagenEntrypoint,
    datagenEntrypointJson: datagenEntrypoint === "" ? "" : JSON.stringify(datagenEntrypoint),
    // The generated project's README must not tell users to hand-draw art the generator just painted.
    TEXTURE_NOTES: spec.textures
      ? "## Textures\n\nGenerated as 16x16 PNGs (64x32 for entities) under `src/main/resources/assets/" +
        ns +
        "/textures/{item,block,entity}/`. They are managed files: to change the art, edit the ModSpec\n(`texture: { style, palette, seed }`) and regenerate - do not edit the PNGs by hand."
      : "## Textures (not generated)\n\nModels reference these 16x16 PNG files - add them before shipping,\notherwise the game shows the missing-texture placeholder:\n\n- src/main/resources/assets/" +
        ns +
        "/textures/item/<item id>.png\n- src/main/resources/assets/" +
        ns +
        "/textures/block/<block id>.png",
    mainClassSimpleName: adapter.mainClassSimpleName,
    mainClassFq: `${packageName}.${adapter.mainClassSimpleName}`,
    ...gradleVars,
  };
}

function makeContext(spec: ModSpecT, adapter: AdapterRecordT, images?: Map<string, Uint8Array>): GenContext {
  return { spec, adapter, vars: buildVars(spec, adapter), warnings: [], images };
}

interface ItemGenOut {
  files: FileEntry[];
  /** Class-body field declarations. */
  itemRegistrations: string[];
  /** Statements placed inside the registry class init() for the mod's own tab. */
  tabEntries: string[];
  /** Statements placed inside init() that hook vanilla creative tabs. */
  groupHooks: string[];
  langEntries: Record<string, string>;
}

function genItems(ctx: GenContext): ItemGenOut {
  const out: ItemGenOut = { files: [], itemRegistrations: [], tabEntries: [], groupHooks: [], langEntries: {} };
  for (const item of ctx.spec.content.items) {
    const constName = toPascalCase(item.id);
    const display = item.name ?? toDisplayName(item.id);
    const v = { ...ctx.vars, CONST: constName, CONST_UPPER: toScreamingSnake(constName), REG_NAME: item.id, DISPLAY: display, id: item.id };
    const groupExpr = item.group != null ? ctx.adapter.vanillaGroups[item.group] : undefined;
    // Two eras route an item into a vanilla tab in two different ways: older versions bind the tab
    // while the item is constructed (Item.Properties#tab on 1.16), newer ones add it after the fact
    // through a registration hook (ItemGroupEvents on 1.19+). Which form applies is adapter data -
    // itemGroupSuffix renders the construction-time one, itemRegistrationGroup the hook. An adapter
    // that ships neither keeps vanilla groups unavailable and the spec falls back to the mod's tab.
    const groupSuffix =
      groupExpr === undefined || ctx.adapter.templates.itemGroupSuffix === undefined
        ? ""
        : renderTemplate(ctx.adapter.templates.itemGroupSuffix, { ...v, GROUP_EXPR: groupExpr }, "itemGroupSuffix");
    const settingsKey = item.maxCount != null ? "itemSettingsMaxCount" : "itemSettings";
    // Durability comes from adapter data for the same reason everything else does: the setter's name
    // is version-specific (Item.Properties#durability from 1.13, Item#setMaxDamage before that), and
    // the engine must not know a single Minecraft API name.
    let durabilitySuffix = "";
    if (item.durability !== undefined) {
      const tpl = ctx.adapter.templates.itemDurabilitySuffix;
      if (tpl === undefined) {
        throw new McmodError(
          "ADAPTER_INVALID",
          `Adapter ${ctx.adapter.id} does not offer item durability; drop "durability" from item "${item.id}" or use an adapter that ships the "itemDurabilitySuffix" template`,
          { adapterId: ctx.adapter.id, templateKey: "itemDurabilitySuffix", item: item.id },
        );
      }
      durabilitySuffix = renderTemplate(tpl, { ...v, DURABILITY: String(item.durability) }, "itemDurabilitySuffix");
    }
    const settings = renderTemplate(
      ctx.adapter.templates[settingsKey]!,
      {
        ...v,
        MAX_COUNT: String(item.maxCount ?? 64),
        DURABILITY_SUFFIX: durabilitySuffix,
        GROUP_EXPR: groupExpr ?? "",
        GROUP_SUFFIX: groupSuffix,
      },
      settingsKey,
    );
    const behaviorExpr = ctx.adapter.itemBehaviors[item.behavior];
    if (behaviorExpr === undefined) {
      throw new McmodError(
        "SPEC_INVALID",
        `item "${item.id}": behavior "${item.behavior}" is not offered by adapter ${ctx.adapter.id}; available: ${Object.keys(ctx.adapter.itemBehaviors).join(", ")}`,
        { id: item.id, behavior: item.behavior },
      );
    }
    const itemCtor = renderTemplate(behaviorExpr, { ...v, SETTINGS: settings }, `itemBehaviors.${item.behavior}`);
    let registration: string;
    if (item.group != null && groupExpr != null) {
      registration = renderTemplate(ctx.adapter.templates.itemRegistration!, { ...v, SETTINGS: settings, ITEM_CTOR: itemCtor }, "itemRegistration");
      // An adapter whose version binds the tab at construction time leaves this empty on purpose.
      const hook = renderTemplate(
        ctx.adapter.templates.itemRegistrationGroup!,
        { ...v, SETTINGS: settings, ITEM_CTOR: itemCtor, GROUP_EXPR: groupExpr },
        "itemRegistrationGroup",
      );
      if (hook.trim() !== "") out.groupHooks.push(hook);
    } else {
      if (item.group != null) {
        ctx.warnings.push(`item "${item.id}": unknown group "${item.group}" for adapter ${ctx.adapter.id}; placed in the mod's own tab`);
      }
      registration = renderTemplate(ctx.adapter.templates.itemRegistration!, { ...v, SETTINGS: settings, ITEM_CTOR: itemCtor }, "itemRegistration");
      out.tabEntries.push(renderTemplate(ctx.adapter.templates.tabEntryLineItem!, { ...v }, "tabEntryLineItem"));
    }
    out.itemRegistrations.push(registration);
    // Model shape is a spec choice; the JSON body itself is adapter data, so a version that changes
    // the parent model only needs a data edit. Adapters without the variant get a fixable error.
    const itemModelKey = item.model === "handheld" ? "itemModelHandheld" : "itemModel";
    const itemModelTpl = ctx.adapter.templates[itemModelKey];
    if (itemModelTpl === undefined) {
      throw new McmodError(
        "ADAPTER_INVALID",
        `Adapter ${ctx.adapter.id} does not offer item model "${item.model}"; use "generated" or pick an adapter that ships the "${itemModelKey}" template`,
        { adapterId: ctx.adapter.id, templateKey: itemModelKey, item: item.id },
      );
    }
    out.files.push({
      path: renderPath(ctx.adapter.contentPaths.itemModel, v, "contentPaths.itemModel"),
      content: renderTemplate(itemModelTpl, v, itemModelKey),
      managed: true, executable: false, reason: `item:${item.id}:model`,
    });
    out.langEntries[renderTemplate(ctx.adapter.langKeys.item, { namespace: ctx.vars.namespace!, id: item.id }, "langKeys.item")] = display;
  }
  return out;
}

interface BlockGenOut {
  files: FileEntry[];
  blockRegistrations: string[];
  tabEntries: string[];
  langEntries: Record<string, string>;
}

function genBlocks(ctx: GenContext): BlockGenOut {
  const out: BlockGenOut = { files: [], blockRegistrations: [], tabEntries: [], langEntries: {} };
  const mineable: Record<string, string[]> = {};
  const lootTemplate = ctx.adapter.templates.lootTable;
  const lootPath = ctx.adapter.contentPaths.lootTable;
  for (const block of ctx.spec.content.blocks) {
    const constName = toPascalCase(block.id);
    const display = block.name ?? toDisplayName(block.id);
    // {{tool}} is part of the block's variable set, not just the settings render: a version that
    // expresses the harvest tool in code (Block#setHarvestLevel before tags existed) needs it at
    // registration time, where the setter returns void and so cannot be chained into the settings.
    // Hardness/resistance/tool are part of the block's variable set rather than just the settings
    // render: a version that applies them as setters (Block#setHardness before 1.13) needs them at
    // registration time, where the constructor only takes a Material.
    const v = {
      ...ctx.vars,
      CONST: constName,
      CONST_UPPER: toScreamingSnake(constName),
      REG_NAME: block.id,
      DISPLAY: display,
      id: block.id,
      tool: block.tool,
      HARDNESS: String(block.hardness),
      RESISTANCE: String(block.resistance),
    };
    const settingsKey = block.tool === "none" ? "blockSettingsNoTool" : "blockSettings";
    const settings = renderTemplate(ctx.adapter.templates[settingsKey]!, v, settingsKey);
    const blockModelKey = block.model === "cube_column" ? "blockModelColumn" : "blockModel";
    const blockModelTpl = ctx.adapter.templates[blockModelKey];
    if (blockModelTpl === undefined) {
      throw new McmodError(
        "ADAPTER_INVALID",
        `Adapter ${ctx.adapter.id} does not offer block model "${block.model}"; use "cube_all" or pick an adapter that ships the "${blockModelKey}" template`,
        { adapterId: ctx.adapter.id, templateKey: blockModelKey, block: block.id },
      );
    }
    out.blockRegistrations.push(renderTemplate(ctx.adapter.templates.blockRegistration!, { ...v, SETTINGS: settings }, "blockRegistration"));
    out.tabEntries.push(renderTemplate(ctx.adapter.templates.tabEntryLineBlock!, { ...v }, "tabEntryLineBlock"));
    out.files.push(
      {
        path: renderPath(ctx.adapter.contentPaths.blockState, v, "contentPaths.blockState"),
        content: renderTemplate(ctx.adapter.templates.blockState!, v, "blockState"),
        managed: true, executable: false, reason: `block:${block.id}:blockstate`,
      },
      {
        path: renderPath(ctx.adapter.contentPaths.blockModel, v, "contentPaths.blockModel"),
        content: renderTemplate(blockModelTpl, v, blockModelKey),
        managed: true, executable: false, reason: `block:${block.id}:model`,
      },
      {
        path: renderPath(ctx.adapter.contentPaths.blockItemModel, v, "contentPaths.blockItemModel"),
        content: renderTemplate(ctx.adapter.templates.blockItemModel!, v, "blockItemModel"),
        managed: true, executable: false, reason: `block:${block.id}:itemModel`,
      },
    );
    // Block loot tables are 1.14+. Before that a plain Block drops itself with no data file, so the
    // slice is skipped rather than emitting a file the game would ignore.
    if (lootTemplate !== undefined && lootPath !== undefined) {
      out.files.push({
        path: renderPath(lootPath, v, "contentPaths.lootTable"),
        content: renderTemplate(lootTemplate, v, "lootTable"),
        managed: true, executable: false, reason: `block:${block.id}:loot`,
      });
    }
    if (block.tool !== "none") {
      (mineable[block.tool] ??= []).push(`${ctx.vars.namespace}:${block.id}`);
    }
    out.langEntries[renderTemplate(ctx.adapter.langKeys.block, { namespace: ctx.vars.namespace!, id: block.id }, "langKeys.block")] = display;
  }
  // The mineable tag is a slice, like UI/recipes/entities: a version that has no datapack tags
  // expresses the harvest tool in code instead (see blockRegistration), so the tag is skipped
  // rather than emitted as a file the game would ignore.
  const tagTemplate = ctx.adapter.templates.mineableTag;
  const tagPath = ctx.adapter.contentPaths.mineableTag;
  if (tagTemplate !== undefined && tagPath !== undefined) {
    for (const [tool, values] of Object.entries(mineable)) {
      // Match the template indent (tabs) so generated tag files stay consistently formatted.
      const valuesJson = values.map((s) => `"${s}"`).join(",\n\t\t");
      out.files.push({
        path: renderPath(tagPath, { ...ctx.vars, tool }, "contentPaths.mineableTag"),
        content: renderTemplate(tagTemplate, { ...ctx.vars, VALUES: valuesJson, tool }, "mineableTag"),
        managed: true, executable: false, reason: `block:tags:mineable:${tool}`,
      });
    }
  }
  return out;
}

